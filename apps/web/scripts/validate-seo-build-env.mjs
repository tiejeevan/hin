#!/usr/bin/env node
/**
 * Resolve and validate SEO URLs for production web builds.
 * Writes .env.production.local so Vite sees VITE_* vars in CI (e.g. Cloudflare Pages).
 */

import fs from 'node:fs';
import path from 'node:path';

const isProdBuild = process.env.NODE_ENV === 'production' || process.argv.includes('--production');

function fail(message) {
  console.error(`SEO build error: ${message}`);
  process.exit(1);
}

function readWranglerVars(cwd) {
  const filePath = path.join(cwd, 'wrangler.toml');
  if (!fs.existsSync(filePath)) return {};

  const text = fs.readFileSync(filePath, 'utf8');
  const section = text.match(/\[vars\]\s*([\s\S]*?)(?=\n\[|\s*$)/);
  if (!section) return {};

  const vars = {};
  for (const line of section[1].split('\n')) {
    const match = line.match(/^([A-Z0-9_]+)\s*=\s*"([^"]+)"/);
    if (match) vars[match[1]] = match[2];
  }
  return vars;
}

function validateUrl(name, value) {
  if (!value || !value.trim()) {
    fail(`${name} is required for production web builds. Set VITE_${name.replace('VITE_', '')}, SITE_URL/API_PUBLIC_URL in CI, or SITE_URL in apps/web/wrangler.toml [vars].`);
  }
  const trimmed = value.replace(/\/$/, '');
  if (trimmed.includes('__HIN_')) {
    fail(`${name} still contains build placeholders (${trimmed}).`);
  }
  if (/localhost|127\.0\.0\.1/i.test(trimmed)) {
    fail(`${name} must not use localhost in production builds (got ${trimmed}).`);
  }
  try {
    const parsed = new URL(trimmed);
    if (parsed.protocol !== 'https:') {
      fail(`${name} must use https in production builds (got ${trimmed}).`);
    }
  } catch {
    fail(`${name} is not a valid URL (got ${trimmed}).`);
  }
  return trimmed;
}

function resolveBuildUrls(cwd) {
  const wranglerVars = readWranglerVars(cwd);

  const siteUrl =
    process.env.VITE_SITE_URL
    || process.env.SITE_URL
    || wranglerVars.SITE_URL;

  // Browser API origin — same host as the web app unless explicitly overridden.
  // Do not use Pages runtime API_URL (workers.dev internal fetch).
  const apiUrl =
    process.env.VITE_API_URL
    || process.env.API_PUBLIC_URL
    || process.env.SITE_URL
    || wranglerVars.API_PUBLIC_URL
    || wranglerVars.SITE_URL;

  return {
    siteUrl: validateUrl('VITE_SITE_URL', siteUrl),
    apiUrl: validateUrl('VITE_API_URL', apiUrl),
  };
}

if (isProdBuild) {
  const cwd = process.cwd();
  const { siteUrl, apiUrl } = resolveBuildUrls(cwd);

  const envFile = path.join(cwd, '.env.production.local');
  fs.writeFileSync(
    envFile,
    `# Generated by scripts/validate-seo-build-env.mjs — do not commit\nVITE_SITE_URL=${siteUrl}\nVITE_API_URL=${apiUrl}\n`,
  );

  console.log(`SEO build URLs: SITE=${siteUrl} API=${apiUrl}`);
}
